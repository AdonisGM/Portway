//! What the system clipboard tells without reading its content: whether it
//! changed, and whether whatever put the text there marked it as not to be
//! copied around (password managers do). Reading the content itself is left
//! to the clipboard plugin.

/// A number that changes whenever the clipboard does; `None` where this
/// platform has no cheap way to know (then auto-send is unavailable).
pub fn change_count() -> Option<u64> {
    #[cfg(target_os = "macos")]
    {
        use objc2_app_kit::NSPasteboard;
        let pb = NSPasteboard::generalPasteboard();
        return Some(pb.changeCount() as u64);
    }
    #[cfg(windows)]
    {
        // SAFETY: no arguments, no pointers.
        return Some(unsafe { windows_sys::Win32::System::DataExchange::GetClipboardSequenceNumber() } as u64);
    }
    #[allow(unreachable_code)]
    None
}

/// The clipboard's content is marked sensitive or temporary by the app that
/// put it there. Such text is never sent automatically.
pub fn is_sensitive() -> bool {
    #[cfg(target_os = "macos")]
    {
        use objc2_app_kit::NSPasteboard;
        // The nspasteboard.org conventions, honoured by password managers and clipboard managers.
        const MARKERS: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
        let pb = NSPasteboard::generalPasteboard();
        let Some(types) = pb.types() else { return false };
        return types.iter().any(|t| MARKERS.contains(&t.to_string().as_str()));
    }
    #[cfg(windows)]
    {
        use windows_sys::Win32::System::DataExchange::{IsClipboardFormatAvailable, RegisterClipboardFormatW};
        // Formats Windows' own clipboard history and password managers use to say "do not keep this".
        const MARKERS: [&str; 2] = ["ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore"];
        return MARKERS.iter().any(|name| {
            let wide: Vec<u16> = name.encode_utf16().chain(std::iter::once(0)).collect();
            // SAFETY: `wide` is NUL-terminated and outlives the call.
            let format = unsafe { RegisterClipboardFormatW(wide.as_ptr()) };
            format != 0 && unsafe { IsClipboardFormatAvailable(format) } != 0
        });
    }
    #[allow(unreachable_code)]
    false
}
